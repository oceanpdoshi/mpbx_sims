#!/bin/bash
# Same sweep as submit_geometry_sweep.sh, launched the way the SuperCloud docs recommend for many
# independent tasks: LLsub "triples" [NODES, NPPN, NTPP]. LLsub reserves NODES whole nodes and starts
# NPPN processes on each (one geometry at a time per process, NTPP cores each); process r of
# LLSUB_SIZE = NODES·NPPN solves rows r, r + LLSUB_SIZE, ... of the geometry list.
# Run on a SuperCloud LOGIN node:
#
#   bash chunked_sweep/supercloud/submit_geometry_sweep_triples.sh my_geoms.csv
#   bash chunked_sweep/supercloud/submit_geometry_sweep_triples.sh --resume outputs/<run folder>
#
# Notes (README §4.4): LLsub ignores its command-line options if the script has #SBATCH lines, so
# the job script below has none; the time limit is LLsub's default (check `LLsub -h`, e.g. for a
# time option, before long runs); logs go to <run>/logs/LLSUB.<n>/. Nothing is collected
# automatically: run `python chunked_sweep/collect_run.py <run>` afterwards (seconds).

# ============================== settings ==============================
RUN_NAME="tfln_sweep"
FIELDS=none             # all | none
NODES=8                 # whole nodes (your allocation: 8 xeon-p8 nodes)
NPPN=2                  # geometries solved at the same time on each node (1, 2, 4 ...)
NTPP=24                 # cores per geometry; NPPN x NTPP must be <= 48
CORES_PER_WORKER=1      # cores per mode-solver process inside a geometry
OUT_ROOT=""             # empty = <repo>/outputs
# ======================================================================

set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/lib_submit.sh"
OUT_ROOT="${OUT_ROOT:-$REPO/outputs}"
(( NPPN * NTPP <= 48 )) || { echo "ERROR: NPPN x NTPP = $((NPPN * NTPP)) > 48 cores per node"; exit 1; }
command -v LLsub >/dev/null 2>&1 || { echo "ERROR: LLsub not found (run on a SuperCloud login node)"; exit 1; }

RESUME=""
CSV=""
while [ $# -gt 0 ]; do
    case "$1" in
        --resume) RESUME="$2"; shift 2 ;;
        -*) echo "unknown option $1"; exit 1 ;;
        *) CSV="$1"; shift ;;
    esac
done
check_env

if [ -n "$RESUME" ]; then
    RUN_DIR="$(cd "$RESUME" && pwd)"
    [ -f "$RUN_DIR/run_args.txt" ] || { echo "ERROR: $RUN_DIR/run_args.txt not found"; exit 1; }
    read -r -a ARGS < "$RUN_DIR/run_args.txt"
else
    [ -n "$CSV" ] && [ -f "$CSV" ] || { echo "usage: $0 GEOMETRIES.csv   or   $0 --resume RUN_DIR"; exit 1; }
    check_geometry_csv "$CSV"                              # rib types; a bad row stops here
    RUN_DIR="$(new_run_dir "$OUT_ROOT" "$RUN_NAME")"
    snapshot_code "$RUN_DIR"
    cp "$CSV" "$RUN_DIR/geometries.csv"
    ARGS=(--fields "$FIELDS" --cores-per-worker "$CORES_PER_WORKER")
    echo "${ARGS[*]}" > "$RUN_DIR/run_args.txt"
fi

# The job script, with this run's paths written into it (LLsub runs it on every node).
JOB="$RUN_DIR/code/chunked_sweep/supercloud/job_triples_$(date +%H%M%S).sh"
cat > "$JOB" <<EOF
#!/bin/bash
# generated by submit_geometry_sweep_triples.sh for $RUN_DIR
source /etc/profile
source "$RUN_DIR/code/chunked_sweep/supercloud/common_env.sh"
echo "=== \$(date '+%F %T')  LLSUB_RANK=\$LLSUB_RANK of LLSUB_SIZE=\$LLSUB_SIZE  node \$(hostname)  nproc \$(nproc)"
cd "$RUN_DIR"
"$PY" -u "$RUN_DIR/code/chunked_sweep/run_geometry.py" --out "$RUN_DIR" ${ARGS[*]} \\
    --geom-csv "$RUN_DIR/geometries.csv" --task "\$LLSUB_RANK" --n-tasks "\$LLSUB_SIZE" \\
    --max-cores $NTPP --cpu-slice \$(( LLSUB_RANK % $NPPN ))
status=\$?
echo "=== \$(date '+%F %T')  exit status \$status"
exit \$status
EOF
chmod u+x "$JOB"
write_run_info "$RUN_DIR" "submit    submit_geometry_sweep_triples.sh: LLsub [$NODES,$NPPN,$NTPP]" "job       $JOB"

cd "$RUN_DIR/logs"                                   # LLsub writes its LLSUB.<n>/ log folder here
LLsub "$JOB" "[$NODES,$NPPN,$NTPP]"
echo "submitted -> $RUN_DIR   (status: LLstat; logs: $RUN_DIR/logs/LLSUB.*/)"
echo "afterwards: $PY $SC_DIR/../collect_run.py $RUN_DIR"
echo "resume:     bash $SC_DIR/submit_geometry_sweep_triples.sh --resume $RUN_DIR"
